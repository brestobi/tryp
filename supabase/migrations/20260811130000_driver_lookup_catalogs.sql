-- Native Flutter onboarding preloads these small catalogs, while these RPCs
-- remain available for server-side typeahead and future admin tooling.
CREATE OR REPLACE FUNCTION public.search_driver_vehicle_makes(
  p_query TEXT DEFAULT '',
  p_limit INTEGER DEFAULT 25
)
RETURNS TABLE (name TEXT)
LANGUAGE SQL STABLE SECURITY INVOKER SET search_path = public
AS $$
  SELECT m.name
  FROM public.driver_vehicle_makes m
  WHERE NULLIF(trim(p_query), '') IS NULL
     OR m.name ILIKE '%' || trim(p_query) || '%'
  ORDER BY CASE WHEN m.name ILIKE trim(p_query) || '%' THEN 0 ELSE 1 END, m.name
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 25), 1), 1000);
$$;

CREATE OR REPLACE FUNCTION public.search_driver_vehicle_colors(
  p_query TEXT DEFAULT '',
  p_limit INTEGER DEFAULT 25
)
RETURNS TABLE (name TEXT)
LANGUAGE SQL STABLE SECURITY INVOKER SET search_path = public
AS $$
  SELECT c.name
  FROM public.driver_vehicle_colors c
  WHERE NULLIF(trim(p_query), '') IS NULL
     OR c.name ILIKE '%' || trim(p_query) || '%'
  ORDER BY CASE WHEN c.name ILIKE trim(p_query) || '%' THEN 0 ELSE 1 END, c.name
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 25), 1), 1000);
$$;

CREATE OR REPLACE FUNCTION public.search_driver_operating_areas(
  p_query TEXT DEFAULT '',
  p_limit INTEGER DEFAULT 25
)
RETURNS TABLE (name TEXT, locality_type TEXT)
LANGUAGE SQL STABLE SECURITY INVOKER SET search_path = public
AS $$
  SELECT a.name, a.locality_type
  FROM public.driver_operating_areas a
  WHERE NULLIF(trim(p_query), '') IS NULL
     OR a.name ILIKE '%' || trim(p_query) || '%'
  ORDER BY CASE WHEN a.name ILIKE trim(p_query) || '%' THEN 0 ELSE 1 END,
           CASE WHEN a.route_group = 'Tzaneen–The Oaks R36 corridor' THEN 0 ELSE 1 END,
           a.route_order,
           a.name
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 25), 1), 1000);
$$;


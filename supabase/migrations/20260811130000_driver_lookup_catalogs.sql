-- Driver onboarding lookup catalogs.
-- These are deliberately separate from profiles so onboarding can offer
-- searchable, consistent values without allowing drivers to edit the catalog.

CREATE TABLE IF NOT EXISTS public.driver_vehicle_makes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.driver_vehicle_colors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.driver_operating_areas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  locality_type TEXT NOT NULL DEFAULT 'village'
    CHECK (locality_type IN ('city', 'town', 'township', 'village', 'area')),
  route_group TEXT NOT NULL DEFAULT 'Tzaneen–The Oaks R36 corridor',
  route_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

ALTER TABLE public.driver_operating_areas
  ADD COLUMN IF NOT EXISTS route_order INTEGER NOT NULL DEFAULT 0;

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE INDEX IF NOT EXISTS idx_driver_vehicle_makes_name
  ON public.driver_vehicle_makes (lower(name));
CREATE INDEX IF NOT EXISTS idx_driver_vehicle_makes_trgm
  ON public.driver_vehicle_makes USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_driver_vehicle_colors_name
  ON public.driver_vehicle_colors (lower(name));
CREATE INDEX IF NOT EXISTS idx_driver_vehicle_colors_trgm
  ON public.driver_vehicle_colors USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_driver_operating_areas_name
  ON public.driver_operating_areas (lower(name));
CREATE INDEX IF NOT EXISTS idx_driver_operating_areas_trgm
  ON public.driver_operating_areas USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_driver_operating_areas_route_order
  ON public.driver_operating_areas (route_group, route_order, lower(name));

ALTER TABLE public.driver_vehicle_makes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.driver_vehicle_colors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.driver_operating_areas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "authenticated_can_read_driver_vehicle_makes"
  ON public.driver_vehicle_makes;
CREATE POLICY "authenticated_can_read_driver_vehicle_makes"
  ON public.driver_vehicle_makes FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated_can_read_driver_vehicle_colors"
  ON public.driver_vehicle_colors;
CREATE POLICY "authenticated_can_read_driver_vehicle_colors"
  ON public.driver_vehicle_colors FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated_can_read_driver_operating_areas"
  ON public.driver_operating_areas;
CREATE POLICY "authenticated_can_read_driver_operating_areas"
  ON public.driver_operating_areas FOR SELECT TO authenticated USING (true);

GRANT SELECT ON public.driver_vehicle_makes TO authenticated;
GRANT SELECT ON public.driver_vehicle_colors TO authenticated;
GRANT SELECT ON public.driver_operating_areas TO authenticated;

